const dictionaries: Record<DashboardLang, Record<DashboardKey, string>> = { en, hy, ru };

export function dashboardText(lang: DashboardLang, key: DashboardKey): string {
  return dictionaries[lang][key];
}

export function dashboardLang(): DashboardLang {
  const value = localStorage.getItem("teta2-product-language") ?? localStorage.getItem("teta2-v4-language") ?? document.documentElement.lang;
  if (value.toLowerCase().startsWith("hy")) return "hy";
  if (value.toLowerCase().startsWith("ru")) return "ru";
  return "en";
}

export function dashboardLocale(lang: DashboardLang): string {
  return lang === "hy" ? "hy-AM" : lang === "ru" ? "ru-RU" : "en-US";
}

